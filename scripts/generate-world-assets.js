const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'js', 'world_assets.js');

const generatedNames = [
  'generated_bed',
  'generated_sofa',
  'generated_stove',
  'generated_fridge',
  'generated_toilet',
  'generated_shower',
  'generated_indoor_tree',
  'generated_potted_flower',
  'generated_computer_desk',
  'generated_arcade',
  'generated_treadmill',
  'generated_fountain',
  'generated_crib',
  'generated_workbench',
  'generated_telescope',
  'generated_hot_tub',
  'generated_kitchen_sink',
  'generated_microwave',
  'generated_espresso',
  'generated_dishwasher',
  'generated_bathroom_vanity',
  'generated_flat_tv',
  'generated_stereo',
  'generated_game_console',
  'generated_aquarium',
  'generated_standing_mirror',
  'generated_bbq_grill',
  'generated_weight_bench',
  'generated_changing_table',
  'generated_3d_printer',
  'generated_fireplace',
  'generated_vanity',
];

const generatedAssetLimit = Number.parseInt(process.env.SIMLIFE_GENERATED_ASSET_LIMIT || '', 10);
const selectedGeneratedNames = Number.isInteger(generatedAssetLimit)
  ? generatedNames.slice(0, Math.max(0, generatedAssetLimit))
  : generatedNames;

const entries = Object.fromEntries(selectedGeneratedNames.map(name => [
  name,
  `assets/custom/generated_furniture/${name}.png`,
]));

function addDirectional(prefix, directory, filePrefix) {
  entries[`${prefix}_e`] = `${directory}/${filePrefix}_E.png`;
  entries[`${prefix}_n`] = `${directory}/${filePrefix}_N.png`;
}

const library = 'assets/kenney_library/Isometric';
addDirectional('library_bookstand', library, 'bookStand');
addDirectional('library_candle_double', library, 'candleStandDouble');
addDirectional('library_display_books', library, 'displayCaseBooks');
addDirectional('library_display_open', library, 'displayCaseOpen');
addDirectional('library_carpet_small', library, 'floorCarpetSmall');
addDirectional('library_bookcase', library, 'bookcaseBooks');
addDirectional('library_bookcase_ladder', library, 'bookcaseBooksLadder');
addDirectional('library_table_large', library, 'longTableLarge');
addDirectional('library_table_chairs', library, 'longTableChairs');
addDirectional('library_table_decorated', library, 'longTableDecoratedChairsBooks');

const dungeon = 'assets/kenney_dungeon/Isometric';
addDirectional('dungeon_chair', dungeon, 'chair');
addDirectional('dungeon_round_table', dungeon, 'tableRound');
addDirectional('dungeon_short_table_chairs', dungeon, 'tableShortChairs');
addDirectional('dungeon_crates', dungeon, 'woodenCrates');
addDirectional('dungeon_barrels', dungeon, 'barrelsStacked');
addDirectional('dungeon_chest_open', dungeon, 'chestOpen');

const farm = 'assets/kenney_minifarm/Isometric';
addDirectional('farm_hay_bales', farm, 'hayBales');
addDirectional('farm_hay_stack', farm, 'hayBalesStacked');
addDirectional('farm_sack', farm, 'sack');
addDirectional('farm_supply_crate', farm, 'sacksCrate');
addDirectional('farm_fence_low', farm, 'fenceLow');
addDirectional('farm_fence_high', farm, 'fenceHigh');
addDirectional('farm_corn_young', farm, 'cornYoung');
addDirectional('farm_plot', farm, 'dirtFarmland');
addDirectional('farm_ladder', farm, 'ladderStand');

const lines = [
  '// Generated by scripts/generate-world-assets.js',
  '// Curated source-pack and generated household sprites for offline runtime use.',
  'window.SIM_ASSETS = Object.assign(window.SIM_ASSETS || {}, {',
];

for (const [key, relativePath] of Object.entries(entries)) {
  const filePath = path.join(root, ...relativePath.split('/'));
  if (!fs.existsSync(filePath)) throw new Error(`Missing world asset source: ${relativePath}`);
  const data = fs.readFileSync(filePath).toString('base64');
  lines.push(`  ${JSON.stringify(key)}: "data:image/png;base64,${data}",`);
}
lines.push('});', '');

fs.writeFileSync(output, lines.join('\n'), 'utf8');
console.log(`Embedded ${Object.keys(entries).length} curated world textures in ${output}`);
